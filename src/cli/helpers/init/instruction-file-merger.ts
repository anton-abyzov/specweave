// Template parsing
// ---------------------------------------------------------------------------

export function parseTemplate(content: string): ParsedTemplate {
  const lines = content.replace(/\r\n/g, '\n').split('\n');
  const sections: TemplateSection[] = [];
  let cur: { id: string; req: boolean; lines: string[] } | null = null;
  let lastEnd = -1;

  const flush = (): void => {
    if (!cur) return;
    sections.push({
      id: cur.id,
      order: sections.length,
      required: cur.req,
      content: cur.lines.join('\n').trim(),
    });
    cur = null;
  };

  lines.forEach((l, i) => {
    const start = l.match(TEMPLATE_START_RE);
    if (start) {
      flush();
      cur = { id: start[1], req: start[2] === 'required', lines: [] };
      return;
    }
    if (TEMPLATE_END_RE.test(l)) {
      flush();
      lastEnd = i;
      return;
    }
    if (cur) cur.lines.push(l);
  });
  flush();

  const tail = lastEnd >= 0 && sections.length > 0 ? lines.slice(lastEnd + 1).join('\n').trim() : '';
  return { sections, tail };
}

export function parseTemplateSections(content: string): TemplateSection[] {
  return parseTemplate(content).sections;
}

