/**
 * Instruction File Merger (2.0) - CLAUDE.md / AGENTS.md
 *
 * parse → classify → render.
 *
 * File layout produced:
 *   [user content that was above the META line]
 *   <!-- SW:META template=".." version=".." sections=".." -->
 *   <!-- SW:SECTION:id version=".." --> … <!-- SW:END:id -->   (template order)
 *   [user-owned tail: ## Commands / ## Project notes]        (added once)
 *   [all other user content, in original order]
 *
 * Guarantees:
 * - user content (anything outside SW markers) is never dropped
 * - sections removed from the template are deleted, ids reported
 * - a section's version attr changes only when its body changed
 * - idempotent: a second run over the output is byte-identical
 * - broken markers are repaired (body kept as user content), never abort
 * - legacy 1.x files (no markers, or "↓ ORIGINAL ↓" stacks) are stripped of
 *   known 1.x template blocks by heading and de-duplicated
 */

