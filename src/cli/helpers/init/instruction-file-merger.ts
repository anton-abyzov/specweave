export function mergeInstructionFile(
  existing: string | null,
  secs: TemplateSection[] | ParsedTemplate,
  type: TemplateType,
  ver: string,
  name: string,
  opts: MergeOptions = {}
): MergeResult {
  const tpl = normalizeTemplate(secs, opts);
  const ids = tpl.sections.map(s => s.id);

  if (!existing || !existing.trim()) {
    const parts = [genMeta(type, ver, ids)];
    for (const s of tpl.sections) parts.push(wrap(s.id, fillName(s.content, name), ver));
    if (tpl.tail) parts.push(fillName(tpl.tail, name));
    return {
      content: finish(fillCommandPlaceholders(parts.join('\n\n'), opts.commands), null),
      action: 'created',
      updated: [],
      added: ids,
      removed: [],
      preserved: 0,
      warnings: [],
      migration: null,
    };
  }

  const p = parseFile(existing);
  const warnings = [...p.warnings];
  const legacy = p.meta === null && p.sections.length === 0;
  const fromVersion = p.meta?.version ?? p.sections[0]?.version ?? 'unknown';
  const migrating = legacy || majorOf(fromVersion) < TEMPLATE_SCHEMA_MAJOR;

  // --- classify sections -------------------------------------------------
  const fileById = new Map(p.sections.map(s => [s.id, s]));
  const listed = new Set(p.meta?.sections ?? p.sections.map(s => s.id));
  const rendered: FileSection[] = [];
  const updated: string[] = [];
  const added: string[] = [];
  const skipped: string[] = [];

  for (const s of tpl.sections) {
    const body = fillName(s.content, name);
    const cur = fileById.get(s.id);
    if (cur) {
      if (cur.body === body) rendered.push({ id: s.id, version: cur.version || ver, body });
      else {
        rendered.push({ id: s.id, version: ver, body });
        updated.push(s.id);
      }
    } else if (listed.has(s.id) && !s.required) {
      skipped.push(s.id);
    } else {
      rendered.push({ id: s.id, version: ver, body });
      added.push(s.id);
    }
  }
  const tplIds = new Set(ids);
  const removed = p.sections.map(s => s.id).filter(id => !tplIds.has(id));
  const renderedIds = rendered.map(r => r.id);
  const sectionsChanged =
    updated.length > 0 ||
    added.length > 0 ||
    removed.length > 0 ||
    renderedIds.join(',') !== (p.meta?.sections ?? []).join(',');
  const metaVersion = !p.meta || sectionsChanged || migrating ? ver : p.meta.version;

  // --- classify user content ----------------------------------------------
  let legacyMarkers = false;
  const clean = (text: string): string => {
    const r = stripLegacyMarkers(text);
    legacyMarkers = legacyMarkers || r.found;
    return r.text;
  };
  let pre = p.preMeta.map(clean).filter(Boolean);
  let segs = p.segments.map(s => ({ ...s, content: clean(s.content) })).filter(s => s.content);

  if (migrating) {
    pre = pre.map(t => stripLegacyBlocks(t, type, name)).filter(Boolean);
    segs = segs.map(s => ({ ...s, content: stripLegacyBlocks(s.content, type, name) })).filter(s => s.content);
  }
  if (migrating || legacyMarkers) {
    const deduped = dedupeBlocks([...pre, ...segs.map(s => s.content)]);
    const preCount = pre.length;
    pre = deduped.slice(0, preCount).filter(Boolean);
    segs = segs.map((s, i) => ({ ...s, content: deduped[preCount + i] })).filter(s => s.content);
  }

  const attached = new Map<string, string[]>();
  const post: string[] = [];
  const surviving = new Set(renderedIds);
  for (const s of segs) {
    if (!migrating && s.afterId && surviving.has(s.afterId)) {
      const list = attached.get(s.afterId) ?? [];
      list.push(s.content);
      attached.set(s.afterId, list);
    } else {
      post.push(s.content);
    }
  }

  const userText = [...pre, ...segs.map(s => s.content)].join('\n');
  const hasCommands = /^## Commands\s*$/m.test(userText);
  const addTail = migrating && Boolean(tpl.tail) && !hasCommands;

  // --- render --------------------------------------------------------------
  const parts: string[] = [];
  if (pre.length) parts.push(pre.join('\n\n'));
  parts.push(genMeta(type, metaVersion, renderedIds));
  for (const r of rendered) {
    parts.push(wrap(r.id, r.body, r.version));
    for (const a of attached.get(r.id) ?? []) parts.push(a);
  }
  if (addTail) parts.push(fillName(tpl.tail, name));
  parts.push(...post);

  const content = finish(fillCommandPlaceholders(parts.join('\n\n'), opts.commands), p);
  const preserved = pre.length + segs.length;

  if (skipped.length) warnings.push(`Skipped optional sections you removed earlier: ${skipped.join(', ')}`);

  let migration: MigrationInfo | null = null;
  if (migrating && (legacy || removed.length > 0)) {
    migration = { fromVersion: legacy ? 'legacy (no markers)' : fromVersion, removed };
    warnings.push(
      `Upgraded instructions from ${migration.fromVersion} to ${ver}: ` +
        (removed.length ? `removed 1.x sections ${removed.join(', ')}; ` : 'stripped 1.x template blocks; ') +
        'your own notes were kept below the managed block.'
    );
  }

  if (content === existing) {
    return { content, action: 'unchanged', updated: [], added: [], removed: [], preserved, warnings, migration: null };
  }

  return { content, action: 'merged', updated, added, removed, preserved, warnings, migration };
}

/**
 * Strip all SW-managed content from an instruction file, returning only user
 * content (null when nothing is left). Used by `specweave uninstall`.
 */
export function stripSwSections(content: string): string | null {
  if (!content || !content.trim()) return null;
  const p = parseFile(content);
  if (p.meta === null && p.sections.length === 0) return content.trim() || null;
  const parts = [...p.preMeta, ...p.segments.map(s => s.content)]
    .map(t => stripLegacyMarkers(t).text)
    .filter(Boolean);
  return parts.length ? parts.join('\n\n') : null;
}

/**
 * Read specweave's own package.json (not the user's project).
 * Resolves reliably with symlinked installs (nvm, pnpm, npm link); falls back to a directory walk.
 */
export function readSpecweavePackageJson(): Record<string, any> {
  try {
    const require = createRequire(import.meta.url);
    const pkgPath = require.resolve('specweave/package.json');
    return JSON.parse(fs.readFileSync(pkgPath, 'utf-8'));
  } catch {
    // fall back to a directory walk (npm link, running from a checkout)
  }
  try {
    let d = path.dirname(fileURLToPath(import.meta.url));
    for (let i = 0; i < 10; i++) {
      const p = path.join(d, 'package.json');
      if (fs.existsSync(p)) {
        const j = JSON.parse(fs.readFileSync(p, 'utf-8'));
        if (j.name === 'specweave') return j;
      }
      const parent = path.dirname(d);
      if (parent === d) break;
      d = parent;
    }
  } catch {
    // ignore
  }
  return {};
}

export function getPackageVersion(): string {
  return readSpecweavePackageJson().version ?? '0.0.0';
}

/**
 * Minimum Node.js version from specweave's package.json `engines.node` (e.g. ">=20.12.0" → "20.12.0").
 */
export function getMinNodeVersion(): string {
  const engines = readSpecweavePackageJson().engines?.node;
  const m = typeof engines === 'string' ? engines.match(/(\d+)(?:\.(\d+))?(?:\.(\d+))?/) : null;
  if (!m) return '20.0.0';
  return `${m[1]}.${m[2] ?? '0'}.${m[3] ?? '0'}`;
}
