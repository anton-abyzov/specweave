/** Remove "↓ ORIGINAL ↓" / "↓ PROJECT-SPECIFIC ↓" markers and their leading rules. */
function stripLegacyMarkers(text: string): { text: string; found: boolean } {
  const lines = text.split('\n');
  const out: string[] = [];
  let found = false;
  for (const line of lines) {
    if (LEGACY_MARKER_RE.test(line)) {
      found = true;
      while (out.length && (HR_RE.test(out[out.length - 1]) || out[out.length - 1].trim() === '')) out.pop();
      continue;
    }
    out.push(line);
  }
  return { text: out.join('\n').trim(), found };
}

interface Block {
  heading: string | null;
  /** Heading level (1 or 2); meaningless when `heading` is null. */
  level: 1 | 2;
  lines: string[];
}

/**
 * Split markdown into heading blocks. BOTH `#` and `##` start a new block, so a
 * user's own H1 that follows a 1.x template section is never swallowed when
 * that section is stripped.
 */
function splitBlocks(text: string): Block[] {
  const blocks: Block[] = [];
  let cur: Block = { heading: null, level: 2, lines: [] };
  let inFence = false;
  for (const line of text.split('\n')) {
    if (FENCE_RE.test(line)) inFence = !inFence;
    if (!inFence && (H2_RE.test(line) || H1_RE.test(line))) {
      const level: 1 | 2 = H2_RE.test(line) ? 2 : 1;
      blocks.push(cur);
      cur = {
        heading: line.slice(level + 1).replace(/\s*\{#[^}]*\}\s*$/, '').trim(),
        level,
        lines: [],
      };
      continue;
    }
    cur.lines.push(line);
  }
  blocks.push(cur);
  return blocks.filter(b => b.heading !== null || b.lines.some(l => l.trim()));
}

function joinBlocks(blocks: Block[]): string {
  return blocks
    .map(b =>
      (b.heading === null
        ? b.lines.join('\n')
        : ['#'.repeat(b.level) + ' ' + b.heading, ...b.lines].join('\n')
      ).trim()
    )
    .filter(Boolean)
    .join('\n\n');
}

/** Drop raw template copies (`<!-- SECTION:x --> … <!-- /SECTION -->`) and 1.x no-heading lines. */
function stripLegacyLines(text: string, projectName: string): string {
  const out: string[] = [];
  let inTemplate = false;
  let inFence = false;
  for (const line of text.split('\n')) {
    if (FENCE_RE.test(line)) inFence = !inFence;
    if (inFence) {
      if (!inTemplate) out.push(line);
      continue;
    }
    if (TEMPLATE_START_RE.test(line)) {
      inTemplate = true;
      continue;
    }
    if (TEMPLATE_END_RE.test(line)) {
      inTemplate = false;
      continue;
    }
    if (inTemplate) continue;
    if (LEGACY_LINE_RES.some(re => re.test(line))) continue;
    if (H1_RE.test(line)) {
      const title = line.slice(2).trim();
      if (title === projectName || title === '{PROJECT_NAME}') continue;
    }
    out.push(line);
  }
  return out.join('\n');
}

/** Strip known 1.x template H2 blocks; keep everything else verbatim. */
function stripLegacyBlocks(text: string, type: TemplateType, projectName: string): string {
  const known = LEGACY_HEADINGS[type];
  const blocks = splitBlocks(stripLegacyLines(text, projectName));
  const kept: Block[] = [];
  for (const b of blocks) {
    if (b.heading === null || b.level !== 2) {
      kept.push(b);
      continue;
    }
    if (b.heading === SKILL_MEMORIES_HEADING) {
      const lines = b.lines.filter(l => !SKILL_MEMORIES_BOILERPLATE.some(re => re.test(l)));
      const hasContent = lines.some(l => l.trim() && !l.trim().startsWith('<!--'));
      if (hasContent) kept.push({ heading: b.heading, level: b.level, lines });
      continue;
    }
    const sigs = known[b.heading];
    if (sigs) {
      const body = b.lines.join('\n');
      if (sigs.length === 0 || sigs.some(s => body.includes(s))) continue;
    }
    kept.push(b);
  }
  return tidyRules(joinBlocks(kept));
}

/** Collapse rules left behind by removed blocks: no leading/trailing/consecutive `---`. */
function tidyRules(text: string): string {
  const lines = text.split('\n');
  const out: string[] = [];
  for (const line of lines) {
    if (HR_RE.test(line)) {
      const prev = [...out].reverse().find(l => l.trim() !== '');
      if (prev === undefined || HR_RE.test(prev)) continue;
    }
    out.push(line);
  }
  while (out.length && (HR_RE.test(out[out.length - 1]) || out[out.length - 1].trim() === '')) out.pop();
  return out.join('\n').trim();
}

function normalizeKey(text: string): string {
  return text.replace(/\s+/g, ' ').trim().toLowerCase();
}

/**
 * Drop H2 blocks that repeat an earlier identical block (ORIGINAL stacking
 * artifact). Returns one entry per input (possibly empty) so callers keep
 * their positional metadata.
 */
function dedupeBlocks(texts: string[]): string[] {
  const seen = new Set<string>();
  return texts.map(text => {
    const kept: Block[] = [];
    for (const b of splitBlocks(text)) {
      const key = normalizeKey(joinBlocks([b]));
      if (!key || seen.has(key)) continue;
      seen.add(key);
      kept.push(b);
    }
    return joinBlocks(kept);
  });
}

