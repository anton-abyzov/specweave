function wrap(id: string, body: string, version: string): string {
  return `<!-- SW:SECTION:${id} version="${version}" -->\n${body}\n<!-- SW:END:${id} -->`;
}

function genMeta(type: TemplateType, version: string, ids: string[]): string {
  return `<!-- SW:META template="${type}" version="${version}" sections="${ids.join(',')}" -->`;
}

function fillName(text: string, name: string): string {
  return text.replace(/\{PROJECT_NAME\}/g, name);
}

const PLACEHOLDERS: Array<{ key: string; label: string; pick: (c: StackCommands) => string | undefined }> = [
  { key: 'BUILD_CMD', label: 'build', pick: c => c.build },
  { key: 'TEST_CMD', label: 'test', pick: c => c.test },
  { key: 'LINT_CMD', label: 'lint', pick: c => c.lint },
];

function todoComment(label: string): string {
  return `<!-- TODO: add ${label} command -->`;
}

/**
 * Fill `{{BUILD_CMD}}` / `{{TEST_CMD}}` / `{{LINT_CMD}}` (and the TODO comment a
 * previous run may have left) only where they are still present.
 */
export function fillCommandPlaceholders(text: string, commands?: StackCommands): string {
  let out = text;
  for (const p of PLACEHOLDERS) {
    const value = commands ? p.pick(commands) : undefined;
    const token = `{{${p.key}}}`;
    const todo = todoComment(p.label);
    if (!out.includes(token) && !out.includes(todo)) continue;
    const replacement = value ? '`' + value + '`' : todo;
    out = out.split('`' + token + '`').join(replacement);
    out = out.split(token).join(value ?? todo);
    if (value) out = out.split(todo).join('`' + value + '`');
  }
  return out;
}

function majorOf(version: string): number {
  const m = version.match(/^(\d+)/);
  return m ? Number(m[1]) : 0;
}

function normalizeTemplate(secs: TemplateSection[] | ParsedTemplate, opts?: MergeOptions): ParsedTemplate {
  if (Array.isArray(secs)) {
    return { sections: [...secs].sort((a, b) => a.order - b.order), tail: opts?.tail ?? '' };
  }
  return { sections: [...secs.sections].sort((a, b) => a.order - b.order), tail: secs.tail };
}

function finish(text: string, p: ParsedFile | null): string {
  let out = text.trim() + '\n';
  if (p?.eol === '\r\n') out = out.replace(/\n/g, '\r\n');
  if (p?.bom) out = '\uFEFF' + out;
  return out;
}

