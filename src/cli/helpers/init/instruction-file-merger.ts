interface FileSection {
  id: string;
  version: string;
  body: string;
}

interface UserSegment {
  content: string;
  afterId: string | null;
  beforeId: string | null;
}

interface ParsedFile {
  eol: '\n' | '\r\n';
  bom: boolean;
  meta: { template: string | null; version: string; sections: string[] } | null;
  sections: FileSection[];
  preMeta: string[];
  segments: UserSegment[];
  warnings: string[];
}

function parseMetaAttrs(attrs: string): Record<string, string> {
  const out: Record<string, string> = {};
  for (const m of attrs.matchAll(/(\w+)="([^"]*)"/g)) out[m[1]] = m[2];
  return out;
}

function parseFile(raw: string): ParsedFile {
  const bom = raw.charCodeAt(0) === 0xfeff;
  const content = bom ? raw.slice(1) : raw;
  const eol: '\n' | '\r\n' = content.includes('\r\n') ? '\r\n' : '\n';
  const lines = content.replace(/\r\n/g, '\n').split('\n');

  const result: ParsedFile = {
    eol,
    bom,
    meta: null,
    sections: [],
    preMeta: [],
    segments: [],
    warnings: [],
  };

  const metaIndex = lines.findIndex(l => META_RE.test(l));
  if (metaIndex >= 0) {
    const attrs = parseMetaAttrs(lines[metaIndex].match(META_RE)![1]);
    result.meta = {
      template: attrs.template ?? null,
      version: attrs.version ?? 'unknown',
      sections: (attrs.sections ?? '').split(',').map(s => s.trim()).filter(Boolean),
    };
  }

  const seen = new Set<string>();
  let buffer: string[] = [];
  let bufferStart = 0;
  let lastId: string | null = null;

  const flush = (beforeId: string | null): void => {
    const text = buffer.join('\n').trim();
    if (text) {
      if (metaIndex >= 0 && bufferStart < metaIndex) result.preMeta.push(text);
      else result.segments.push({ content: text, afterId: lastId, beforeId });
    }
    buffer = [];
  };

  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];

    if (META_RE.test(line)) {
      if (i === metaIndex) {
        flush(null);
        bufferStart = i + 1;
      } else {
        result.warnings.push('Removed duplicate SW:META line');
      }
      continue;
    }

    const start = line.match(START_RE);
    if (start) {
      const id = start[1];
      let end = -1;
      for (let j = i + 1; j < lines.length; j++) {
        if (START_RE.test(lines[j])) break;
        const e = lines[j].match(END_RE);
        if (e && e[1] === id) {
          end = j;
          break;
        }
      }
      if (end < 0) {
        result.warnings.push(`Repaired unterminated marker for section "${id}" (its text was kept as user content)`);
        continue; // drop the marker line, keep the body as user content
      }
      if (seen.has(id)) {
        result.warnings.push(`Removed duplicate section "${id}"`);
        i = end;
        continue;
      }
      seen.add(id);
      flush(id);
      result.sections.push({ id, version: start[2] ?? '', body: lines.slice(i + 1, end).join('\n').trim() });
      lastId = id;
      i = end;
      bufferStart = i + 1;
      continue;
    }

    if (END_RE.test(line)) {
      result.warnings.push(`Removed stray end marker "${line.trim()}"`);
      continue;
    }

    if (buffer.length === 0) bufferStart = i;
    buffer.push(line);
  }
  flush(null);

  return result;
}

